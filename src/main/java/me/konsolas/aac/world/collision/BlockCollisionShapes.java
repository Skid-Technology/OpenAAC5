    public static CollisionShape findCollisionShape(Entity entity, Block block, Material material, ProtocolVersion version) {
        CollisionShape collisionShape = findCollisionShape(material);
        if (collisionShape != null) {
            return collisionShape;
        } else {
            List<AxisAlignedBoundingBox> blockCollisionBoxes = NativeAccessProvider.getInstance().getBlockCollisionBoxes(block, entity);
            if (blockCollisionBoxes.isEmpty()) {
                return EmptyCollisionShape.getCollisionShape();
            } else if (blockCollisionBoxes.size() == 1) {
                AxisAlignedBoundingBox box = (AxisAlignedBoundingBox) blockCollisionBoxes.get(0);
                AxisAlignedBoundingBox box2 = LegacyCollisionShapes.findAxisAlignedBoundingBox(version, box, material);
                return (CollisionShape) (FULL_BLOCK.equals(box2) ? FullCubeCollisionShape.getCollisionShape() : new SingleBoxCollisionShape(box2));
            } else {
                ArrayList values = new ArrayList(blockCollisionBoxes.size());
                for (AxisAlignedBoundingBox box3 : blockCollisionBoxes) {
                    values.add(LegacyCollisionShapes.findAxisAlignedBoundingBox(version, box3, material));
                }
                return new CompositeCollisionShape(values);
            }
        }
    }

